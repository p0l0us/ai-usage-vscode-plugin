// Keep standalone CLI settings aligned with every setting exposed by VS Code.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const pkg = require('../package.json');
const settings = Object.assign({}, ...pkg.contributes.configuration.map(block => block.properties));
const catalog = Object.entries(settings).map(([key, value]) => ({
  key: key.replace(/^aiUsage\./, ''),
  type: value.enum ? 'enum' : (Array.isArray(value.type) ? value.type.find(type => type !== 'null') : value.type),
  ...(value.enum ? { values: value.enum } : {}),
  ...(value.minimum !== undefined ? { min: value.minimum } : {}),
  ...(value.maximum !== undefined ? { max: value.maximum } : {}),
  ...(Array.isArray(value.type) && value.type.includes('null') ? { nullable: true } : {}),
  ...(value.default !== undefined ? { default: value.default } : {}),
  description: value.markdownDescription || value.description || key
}));
fs.writeFileSync(path.join(root, 'service/src/settingsCatalog.ts'),
  '// Generated by scripts/generate-service-settings.js from package.json. Do not edit.\n' +
  'export const SETTINGS_CATALOG = ' + JSON.stringify(catalog, null, 2) + ';\n');
